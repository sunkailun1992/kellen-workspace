import java.lang.reflect.*;
import java.math.BigDecimal;
import java.net.URI;
import java.sql.*;
import java.time.LocalDateTime;
import java.util.*;

/** 显式启用的 NAS 专用 PG18 隔离回归，只创建/删除本次随机 schema。 */
public final class MigrationPostgresqlTest {
    static void check(boolean condition,String reason){MigrationCore.require(condition,reason);}
    static String rewrite(String sql,String schema) {
        String logical="public.\"codec_fixture\"";
        check(!sql.contains("public.")||sql.contains(logical),"TEST_NAMESPACE_REJECTED");
        return sql.replace(logical,MigrationCore.pg(schema)+".\"codec_fixture\"");
    }
    static Object invoke(Object target,Method method,Object[] args)throws Throwable {
        try{return method.invoke(target,args);}catch(InvocationTargetException e){throw e.getCause();}
    }
    static Connection scoped(Connection actual,String schema) {
        return (Connection)Proxy.newProxyInstance(MigrationPostgresqlTest.class.getClassLoader(),new Class[]{Connection.class},(proxy,method,args)->{
            Object[] rewritten=args==null?null:args.clone();
            if(method.getName().equals("prepareStatement"))rewritten[0]=rewrite((String)rewritten[0],schema);
            Object value=invoke(actual,method,rewritten);
            if(!(value instanceof Statement statement))return value;
            Class<?> api=statement instanceof PreparedStatement?PreparedStatement.class:Statement.class;
            return Proxy.newProxyInstance(MigrationPostgresqlTest.class.getClassLoader(),new Class[]{api},(p,m,a)->{
                Object[] adapted=a==null?null:a.clone();
                if(adapted!=null&&adapted.length>0&&adapted[0] instanceof String sql&&Set.of("execute","executeUpdate","executeQuery").contains(m.getName()))adapted[0]=rewrite(sql,schema);
                if(m.getName().equals("setString")&&(Integer)adapted[0]==1&&adapted[1] instanceof String text&&text.startsWith("public."))adapted[1]=rewrite(text,schema);
                return invoke(statement,m,adapted);
            });
        });
    }
    static MigrationCore.Column column(String name,MigrationCore.Kind kind){return new MigrationCore.Column(name,kind,true,false);}
    static Map<String,Object> run()throws Exception {
        java.util.logging.Logger.getLogger("org.postgresql").setLevel(java.util.logging.Level.OFF);
        String url=System.getenv("FLEET_PG_TEST_URL"),user=System.getenv("FLEET_PG_TEST_USERNAME"),password=System.getenv("FLEET_PG_TEST_PASSWORD");
        check(url!=null&&user!=null&&password!=null,"TEST_PRIVATE_ENV_REQUIRED");
        check(url.startsWith("jdbc:postgresql://"),"TEST_URL_SCHEME");URI uri=URI.create(url.substring(5));
        check(uri.getUserInfo()==null&&uri.getRawPath()!=null&&uri.getRawPath().matches("/fleet_pg_test_[a-z0-9_]+"),"TEST_DATABASE_REJECTED");
        Properties properties=new Properties();properties.setProperty("user",user);properties.setProperty("password",password);properties.setProperty("connectTimeout","3");properties.setProperty("socketTimeout","5");properties.setProperty("ApplicationName","fleet-migration-isolated-test");
        String schema="fleet_migration_"+UUID.randomUUID().toString().replace("-","");boolean created=false;int tests=0;
        try(Connection connection=DriverManager.getConnection(url,properties)) {
            try(Statement statement=connection.createStatement();ResultSet result=statement.executeQuery("SELECT current_database(), current_setting('server_version_num')::integer")) {
                check(result.next()&&result.getString(1).matches("fleet_pg_test_[a-z0-9_]+")&&result.getInt(2)>=180000&&result.getInt(2)<190000,"TEST_DATABASE_REJECTED");
            }
            try {
                try(Statement statement=connection.createStatement()) {
                    statement.execute("CREATE SCHEMA "+MigrationCore.pg(schema));created=true;
                    statement.execute("CREATE TABLE "+MigrationCore.pg(schema)+".codec_fixture (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, text_value text, bool_value boolean, decimal_value numeric(28,9), json_value jsonb, binary_value bytea, time_value timestamp(6) without time zone, float_value double precision)");
                }
                List<MigrationCore.Column> columns=List.of(new MigrationCore.Column("id",MigrationCore.Kind.INTEGER,false,true),column("text_value",MigrationCore.Kind.STRING),column("bool_value",MigrationCore.Kind.BOOLEAN),column("decimal_value",MigrationCore.Kind.DECIMAL),column("json_value",MigrationCore.Kind.JSON),column("binary_value",MigrationCore.Kind.BINARY),column("time_value",MigrationCore.Kind.TIMESTAMP),column("float_value",MigrationCore.Kind.FLOAT));
                List<List<Object>> samples=List.of(
                        Arrays.asList(900000L,"NULL 'quote' 中文",true,new BigDecimal("1234567890123456789.123456789"),"{\"a\":9007199254740993.123456789,\"values\":[null,\"NULL\",1.000,{\"quote\":\"a'b\"}],\"中文\":\"保留\"}",new byte[]{0,1,-1,39},LocalDateTime.of(2026,11,9,13,2,1,123456000),1.2d),
                        Arrays.asList(900001L,"NULL",false,new BigDecimal("-0.000000000"),"null",new byte[0],LocalDateTime.of(2000,1,1,0,0,0),-0d),
                        Arrays.asList(900002L,null,null,null,null,null,null,null));
                MigrationCore.Rows expected=new MigrationCore.Rows(100,16384);connection.setAutoCommit(false);
                String names=String.join(",",columns.stream().map(c->MigrationCore.pg(c.name())).toList());
                try(PreparedStatement insert=connection.prepareStatement("INSERT INTO "+MigrationCore.pg(schema)+".codec_fixture ("+names+") OVERRIDING SYSTEM VALUE VALUES (?,?,?,?,?,?,?,?)")) {
                    for(List<Object> sample:samples) {
                        List<Object> normalized=new ArrayList<>();
                        for(int i=0;i<columns.size();i++){Object value=MigrationCore.normalize(columns.get(i).kind(),sample.get(i),16384);normalized.add(value);MigrationCore.bind(insert,i+1,columns.get(i),value);}
                        check(insert.executeUpdate()==1,"TEST_INSERT_COUNT");expected.add(columns,normalized);
                    }
                }
                connection.commit();tests++;
                var config=new FleetMigration.Config(null,Map.of(),null,"0".repeat(64),null,100,16384,5,"synthetic-nas-window");
                var table=new FleetMigration.Table("github_dev_ai","codec_fixture",columns,List.of(),1_000_000L);Connection namespaced=scoped(connection,schema);
                var expectedStat=new FleetMigration.Stat(expected.count(),expected.finish());
                check(FleetMigration.scan(namespaced,table,false,config,null).equals(expectedStat),"TEST_REAL_ROUNDTRIP_MISMATCH");tests++;
                // 与实际执行器一致：结束自己的只读核验事务，再开始受控写事务。
                connection.rollback();
                try {
                    MigrationCore.transaction(namespaced,()->{
                        try(PreparedStatement insert=connection.prepareStatement("INSERT INTO "+MigrationCore.pg(schema)+".codec_fixture(json_value) VALUES (?)")) {
                            MigrationCore.bind(insert,1,column("json_value",MigrationCore.Kind.JSON),"SYNTHETIC_INVALID_JSON_MUST_NOT_ESCAPE");insert.executeUpdate();
                        }return null;
                    });throw new MigrationCore.Failure("TEST_INVALID_JSON_ACCEPTED");
                }catch(SQLException error){if(!"22P02".equals(error.getSQLState()))throw new MigrationCore.Failure("TEST_INVALID_JSON_STATE",error);check(!MigrationCore.JSON.writeValueAsString(new MigrationCore.Failure("JDBC_OPERATION_FAILED",error).report()).contains("SYNTHETIC_INVALID_JSON"),"TEST_EXCEPTION_LEAK");}tests++;
                check(FleetMigration.scan(namespaced,table,false,config,null).equals(expectedStat),"TEST_ROLLBACK_MISMATCH");tests++;
                var shape=new FleetMigration.Shape("1".repeat(64),Set.of("codec_fixture.id"),Map.of());
                var prepared=new FleetMigration.Prepared(config,null,List.of(table),"1".repeat(64),"2".repeat(64),Map.of("github_dev_ai",namespaced),Map.of("github_dev_ai",shape),Map.of(),"3".repeat(64));
                FleetMigration.calibrate(prepared,"github_dev_ai");
                try(PreparedStatement next=connection.prepareStatement("SELECT nextval(pg_get_serial_sequence(?, 'id'))")) {
                    next.setString(1,MigrationCore.pg(schema)+".codec_fixture");try(ResultSet result=next.executeQuery()){check(result.next()&&result.getLong(1)==1_000_000L,"TEST_SOURCE_COUNTER_NOT_PRESERVED");}
                }tests++;
                try(Statement insert=connection.createStatement();ResultSet result=insert.executeQuery("INSERT INTO "+MigrationCore.pg(schema)+".codec_fixture(text_value) VALUES ('synthetic-generated') RETURNING id")) {check(result.next()&&result.getLong(1)==1_000_001L,"TEST_IDENTITY_NOT_GENERATED");}tests++;
                return Map.of("status","verified","tests",tests,"rows_roundtripped",3,"postgres_major",18,"schema_cleanup_required",true);
            } finally {
                if(!connection.getAutoCommit())connection.rollback();connection.setAutoCommit(true);
                if(created)try(Statement statement=connection.createStatement()){statement.execute("DROP SCHEMA "+MigrationCore.pg(schema)+" CASCADE");}
            }
        }
    }
    public static void main(String[] args) {
        Map<String,Object> result;int code=0;
        try{Map<String,Object> passed=new LinkedHashMap<>(run());passed.remove("schema_cleanup_required");passed.put("schema_cleaned",true);result=passed;}
        catch(MigrationCore.Failure failure){result=failure.report();code=1;}
        catch(SQLException error){result=new MigrationCore.Failure("TEST_JDBC_FAILED",error).report();code=1;}
        catch(Throwable failure){result=Map.of("status","rejected","reason","TEST_INTERNAL_FAILURE");code=1;}
        System.out.println(MigrationCore.JSON.writeValueAsString(result));if(code!=0)System.exit(code);
    }
}
